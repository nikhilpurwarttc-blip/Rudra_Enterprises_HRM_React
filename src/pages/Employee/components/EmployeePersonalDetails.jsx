import InputField from '../../../components/InputField';
import SectionCard from '../../../components/SectionCard';
import Switch from '../../../components/Switch';
import UploadField from '../../../components/UploadField';
import ChoiceChips from '../../../components/ChoiceChips';

const EmployeePersonalDetails = ({ form, errors, setField, setGender, setMaritalStatus, updateForm }) => (
  <SectionCard
    title="Personal Details"
    action={(
      <div className="flex items-center gap-2">
        <span className="text-sm font-medium text-(--color-text)">
          {form.status === 1 ? 'Active' : 'Inactive'}
        </span>
        <Switch
          checked={form.status === 1}
          onClick={() => updateForm((current) => ({ ...current, status: current.status === 1 ? 0 : 1 }))}
          ariaLabel={`${form.status === 1 ? 'Deactivate' : 'Activate'} employee`}
          title="Toggle employee status"
        />
      </div>
    )}
  >
    <div className="space-y-6">
      {/* Section description */}
      {/* <p className="text-sm text-gray-500">
        Update the employee's core personal information and profile picture.
      </p> */}

      {/* Upload Field Container */}
      <div className="sm:col-span-2">
        <UploadField
          label="Employee Photo"
          value={form.image}
          onChange={(image) => updateForm((current) => ({ ...current, image }))}
          accept="image/jpeg,image/png,image/jpg"
          maxSize={2 * 1024 * 1024}
          previewOnSelect
        />
      </div>

      {/* Input grid */}
      <div className="grid grid-cols-1 gap-5 sm:grid-cols-6">
        <div className="sm:col-span-2">
          <InputField
            label="Employee Code"
            value={form.employee_code}
            helperText="Generated by the server."
            disabled
          />
        </div>
        <div className="sm:col-span-2">
          <InputField
            label="Full Name"
            value={form.name}
            onChange={setField('name')}
            error={errors.name}
            required
          />
        </div>
        <div className="sm:col-span-2">
          <InputField
            label="Date of Birth"
            type="date"
            value={form.dob}
            onChange={setField('dob')}
            error={errors.dob}
          />
        </div>

        {/* Placeholder wrapper for alignment consistency */}
        {/* <div className="hidden sm:block" /> */}

        <div className="sm:col-span-3">
          <ChoiceChips
            label="Gender"
            value={form.gender}
            options={['Male', 'Female', 'Other']}
            onChange={setGender}
            error={errors.gender}
          />
        </div>

        <div className="sm:col-span-3">
          <ChoiceChips
            label="Marital Status"
            value={form.marital_status}
            options={['Single', 'Married', 'Divorced', 'Widowed']}
            onChange={setMaritalStatus}
            error={errors.marital_status}
          />
        </div>
      </div>

    </div>
  </SectionCard>
);

export default EmployeePersonalDetails;